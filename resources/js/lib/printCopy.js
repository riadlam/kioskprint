export function formatMoney(amount, locale = 'ar') {
    const value = Math.round(Number(amount || 0) * 100) / 100;
    const plain = Number.isInteger(value) ? String(value) : value.toFixed(2).replace(/\.?0+$/, '');
    const label = copy[locale]?.currency || copy.ar.currency;

    return `${plain} ${label}`;
}





function pages(n, locale) {
    if (locale === 'ar') {
        return n === 1 ? 'صفحة واحدة' : `${n} صفحات`;
    }

    return n === 1 ? '1 page' : `${n} pages`;
}
